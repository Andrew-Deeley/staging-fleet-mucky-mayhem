import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
const target = process.env.FMM_PUBLISH_TARGET;
if (!['github-pages', 'custom-domain'].includes(target)) throw new Error('Choose an explicit publication target.');
const preview = target === 'github-pages';
if (!preview && (process.env.FMM_DOMAIN_CUTOVER_ENABLED !== 'true' || process.env.FMM_PRODUCTION_DOMAIN !== 'fleetmuckymayhem.com')) throw new Error('Custom-domain cutover has not been authorised/configured.');
const source = process.env.GITHUB_SHA;
if (!/^[a-f0-9]{40}$/.test(source || '')) throw new Error('A source commit is required.');
const version = JSON.parse(readFileSync('package.json', 'utf8')).version;
if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error('Set a numeric x.y.z release version in package.json.');
const output = preview ? 'artifacts/production-site' : 'dist';
const html = readFileSync(output + '/index.html', 'utf8');
if (html.includes('/staging-fleet-mucky-mayhem/')) throw new Error('Refusing staging HTML as production.');
if (preview) {
  if (!html.includes('noindex, nofollow') || !html.includes('/fleet-mucky-mayhem/_astro/')) throw new Error('Expected prefixed, non-indexed GitHub production preview.');
  if (existsSync(output + '/CNAME')) throw new Error('GitHub preview must not bind a custom domain.');
} else if (html.includes('noindex') || html.includes('/fleet-mucky-mayhem/')) throw new Error('Expected root-domain production build.');
if (readdirSync(output, {recursive:true}).some(file => /(?:^|[\\/])(?:\.git|node_modules|src)(?:[\\/]|$)|\.map$/.test(String(file)))) throw new Error('Unexpected source or dependency files in production output.');
writeFileSync(output + '/.nojekyll', '');
if (!preview) writeFileSync(output + '/CNAME', 'fleetmuckymayhem.com\n');
writeFileSync(output + '/release-version.json', JSON.stringify({version:'v'+version, source, target})+'\n');
console.log('Prepared v'+version+' for '+target+' from '+source);
